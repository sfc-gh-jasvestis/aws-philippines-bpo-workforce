-- Staffing-gap risk scoring and workforce-event forecast over the synthetic snapshot.
-- Predicts P(staffing-gap event on the team in the next 7 days) per team and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.GAP_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, a.CATEGORY, a.RISK_TIER, a.AVG_TENURE_YEARS,
       r.ABSENCE_PCT, r.AVG_HANDLE_MIN,
       AVG(r.ABSENCE_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS ABSENCE_7D,
       SUM(r.GAP_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS GAPS_30D,
       IFF(SUM(r.GAP_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'GAP', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.TEAM_DAILY r JOIN RAW.TEAMS a ON a.ID = r.ENTITY_ID
-- City-wide typhoon site closures are not team-driven, so they are excluded from training.
WHERE r.EVENT_TYPE <> 'Typhoon site closure';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.GAP_TRAIN AS
SELECT CATEGORY, RISK_TIER, AVG_TENURE_YEARS, ABSENCE_PCT, AVG_HANDLE_MIN, ABSENCE_7D, GAPS_30D, LABEL
FROM ML.GAP_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.GAP_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, RISK_TIER, AVG_TENURE_YEARS, ABSENCE_PCT, AVG_HANDLE_MIN, ABSENCE_7D, GAPS_30D, LABEL
FROM ML.GAP_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.GAP_RISK_MODEL(
  INPUT_DATA => TABLE(ML.GAP_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.GAP_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.GAP_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'AVG_TENURE_YEARS', AVG_TENURE_YEARS,
           'ABSENCE_PCT', ABSENCE_PCT, 'AVG_HANDLE_MIN', AVG_HANDLE_MIN,
           'ABSENCE_7D', ABSENCE_7D, 'GAPS_30D', GAPS_30D)):probability:GAP::FLOAT AS P
  FROM ML.GAP_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'GAP', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'GAP', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'GAP', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'GAP', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per team (label unknown, so excluded from features).
CREATE TABLE ML.GAP_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.GAP_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.GAP_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'RISK_TIER', RISK_TIER, 'AVG_TENURE_YEARS', AVG_TENURE_YEARS,
           'ABSENCE_PCT', ABSENCE_PCT, 'AVG_HANDLE_MIN', AVG_HANDLE_MIN,
           'ABSENCE_7D', ABSENCE_7D, 'GAPS_30D', GAPS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:GAP::FLOAT, 4) AS GAP_PROB_7D,
       CASE WHEN P:probability:GAP::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:GAP::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Company-wide workforce-event forecast (14 days) from the daily series, for real-time workforce planning.
CREATE VIEW ML.DAILY_WORKFORCE_EVENTS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(WORKFORCE_EVENT_COUNT)::FLOAT AS WORKFORCE_EVENT_COUNT
FROM RAW.TEAM_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.EVENT_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_WORKFORCE_EVENTS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'WORKFORCE_EVENT_COUNT'
);

CREATE TABLE ML.EVENT_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS WORKFORCE_EVENT_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.EVENT_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
