-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT team.ID AS ENTITY_ID, team.NAME AS ENTITY_NAME,
       team.REGION, team.CATEGORY, team.RISK_TIER, team.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.CONTACTS_HANDLED) AS CONTACTS_HANDLED,
       SUM(observation.LABOUR_COST_PHP) AS LABOUR_COST_PHP,
       SUM(observation.WORKFORCE_EVENT_COUNT) AS WORKFORCE_EVENT_COUNT,
       SUM(observation.GAP_COUNT) AS GAP_COUNT,
       SUM(observation.SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(observation.QA_DUE) AS QA_DUE,
       SUM(observation.QA_COMPLETED) AS QA_COMPLETED,
       100.0 * (SUM(observation.CONTACTS_HANDLED) - SUM(observation.WORKFORCE_EVENT_COUNT)) / NULLIF(SUM(observation.CONTACTS_HANDLED), 0) AS EVENT_FREE_PCT,
       100.0 * SUM(observation.GAP_COUNT) / NULLIF(SUM(observation.WORKFORCE_EVENT_COUNT), 0) AS EVENT_GAP_PCT,
       100.0 * SUM(observation.QA_COMPLETED) / NULLIF(SUM(observation.QA_DUE), 0) AS QA_COMPLIANCE_PCT,
       AVG(observation.ABSENCE_PCT) AS AVG_ABSENCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.TEAM_DAILY observation
JOIN RAW.TEAMS team ON team.ID = observation.ENTITY_ID
GROUP BY team.ID, team.NAME, team.REGION, team.CATEGORY, team.RISK_TIER, team.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(CONTACTS_HANDLED) AS CONTACTS_HANDLED, SUM(LABOUR_COST_PHP) AS LABOUR_COST_PHP,
       SUM(WORKFORCE_EVENT_COUNT) AS WORKFORCE_EVENT_COUNT, SUM(GAP_COUNT) AS GAP_COUNT,
       100.0 * SUM(GAP_COUNT) / NULLIF(SUM(WORKFORCE_EVENT_COUNT), 0) AS EVENT_GAP_PCT
FROM RAW.TEAM_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.EVENT_TYPE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_TYPE, SUM(WORKFORCE_EVENT_COUNT) AS WORKFORCE_EVENT_COUNT,
       SUM(GAP_COUNT) AS GAP_COUNT,
       SUM(SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(LABOUR_COST_PHP) AS EXPOSED_LABOUR_COST_PHP,
       100.0 * SUM(GAP_COUNT) / NULLIF(SUM(WORKFORCE_EVENT_COUNT), 0) AS EVENT_GAP_PCT
FROM RAW.TEAM_DAILY
WHERE WORKFORCE_EVENT_COUNT > 0
GROUP BY EVENT_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(CONTACTS_HANDLED) AS CONTACTS, SUM(WORKFORCE_EVENT_COUNT) AS EVENTS,
         SUM(GAP_COUNT) AS GAPS, SUM(SLA_BREACHED) AS BREACHES, SUM(LABOUR_COST_PHP) AS LABOUR_COST_PHP,
         SUM(QA_DUE) AS QA_DUE, SUM(QA_COMPLETED) AS QA_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.TEAM_DAILY
), book AS (SELECT COUNT(*) AS TEAM_COUNT FROM RAW.TEAMS),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.TRAINING_RECORDS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Event-Free Contact Rate' AS TITLE,
         100.0 * (CONTACTS - EVENTS) / NULLIF(CONTACTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Workforce Events Logged', EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Staffing-Gap Events', GAPS, '' FROM observations
  UNION ALL SELECT 4, 'Event Gap Rate', 100.0 * GAPS / NULLIF(EVENTS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Client SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Labour Cost (PHP M)', LABOUR_COST_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Contacts Handled', CONTACTS, '' FROM observations
  UNION ALL SELECT 8, 'QA Calibration Compliance', 100.0 * QA_COMPLETED / NULLIF(QA_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Teams Monitored', TEAM_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Training Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Certifications Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.EVENT_TYPE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
